/* Optional live refresh for the prototype: the collector publishes the latest
   delivery day as JSON (CORS-enabled). Falls back silently to the snapshot. */
window.DAM_LIVE = function(){
  var url = 'https://raw.githubusercontent.com/SergejKolesnik/entsoe-ua-prices/hermes-report/latest.json';
  if (!window.fetch) return Promise.resolve(null);
  return fetch(url, { cache: 'no-store' }).then(function(r){ return r.ok ? r.json() : null; }).then(function(j){
    if (!j || !j.hourly || j.hourly.length !== 24 || j.status !== 'complete') return null;
    if ((j.hourly[0] || {}).bidding_zone !== 'UA-IPS') return null;
    var day = j.delivery_date, prices = j.hourly.map(function(h){ return h.price; });
    if (prices.some(function(p){ return typeof p !== 'number' || !isFinite(p); })) return null;
    var fresh = !window.DAM_DATA.days[day];
    window.DAM_DATA.days[day] = prices;
    if (day > window.DAM_DATA.updated) window.DAM_DATA.updated = day;
    return { day: day, fresh: fresh };
  }).catch(function(){ return null; });
};
